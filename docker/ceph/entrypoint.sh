#!/usr/bin/env bash
# Entrypoint for every Ceph container in this repo. The first argument picks
# the role: bootstrap | mon | mgr | osd | mds | rgw | init | health <role>.
#
# Everything is idempotent: a container can be restarted (or a whole
# `make up` re-run) at any point and it either initialises or just starts.
set -euo pipefail

ETC=/etc/ceph
ADMIN_KEYRING="$ETC/ceph.client.admin.keyring"
NET_PREFIX="${CEPH_NET_PREFIX:?CEPH_NET_PREFIX must be set, e.g. 10.250.0}"
MON_IDS=(a b c)
DAEMON_ID="${CEPH_DAEMON_ID:-}"

log() { printf '[%s] %s\n' "${ROLE:-entrypoint}" "$*" >&2; }

mon_ip() {
  # mon a -> .11, b -> .12, c -> .13 (static IPs, see compose.yaml)
  local idx
  for idx in "${!MON_IDS[@]}"; do
    if [[ "${MON_IDS[$idx]}" == "$1" ]]; then
      echo "${NET_PREFIX}.$((11 + idx))"
      return 0
    fi
  done
  return 1
}

wait_for_cluster() {
  log "waiting for monitor quorum"
  until timeout 10 ceph --connect-timeout 5 -k "$ADMIN_KEYRING" -n client.admin quorum_status >/dev/null 2>&1; do
    sleep 2
  done
}

# Copy a keyring from the shared (read-only) config volume into the daemon's
# own data dir, owned by the unprivileged ceph user the daemon drops to.
install_keyring() {
  local src="$1" dir="$2"
  mkdir -p "$dir"
  install -m 0600 -o ceph -g ceph "$src" "$dir/keyring"
}

# ---------------------------------------------------------------------------
# bootstrap: generate fsid, keyrings, monmap and ceph.conf exactly once.
# ---------------------------------------------------------------------------
bootstrap() {
  if [[ -s "$ETC/ceph.conf" ]]; then
    log "already bootstrapped: fsid $(awk '/^fsid/ {print $3}' "$ETC/ceph.conf")"
    return 0
  fi

  local tmp fsid mon_host="" id ip
  # Build everything in a scratch dir and move ceph.conf in last, so a crash
  # half-way through leaves no ceph.conf and the next run starts over.
  rm -rf "$ETC"/.bootstrap.*
  tmp="$(mktemp -d "$ETC/.bootstrap.XXXXXX")"
  fsid="$(cat /proc/sys/kernel/random/uuid)"
  log "generating new cluster, fsid $fsid"

  for id in "${MON_IDS[@]}"; do
    ip="$(mon_ip "$id")"
    mon_host+="${mon_host:+,}[v2:${ip}:3300,v1:${ip}:6789]"
  done

  # Keyrings. The mon keyring holds every bootstrap identity; `ceph-mon --mkfs`
  # imports them into the auth database together with their caps.
  ceph-authtool --create-keyring "$tmp/ceph.mon.keyring" --gen-key -n mon. --cap mon 'allow *' >/dev/null
  ceph-authtool --create-keyring "$tmp/ceph.client.admin.keyring" --gen-key -n client.admin \
    --cap mon 'allow *' --cap osd 'allow *' --cap mds 'allow *' --cap mgr 'allow *'
  ceph-authtool --create-keyring "$tmp/ceph.client.bootstrap-osd.keyring" --gen-key -n client.bootstrap-osd \
    --cap mon 'profile bootstrap-osd' --cap mgr 'allow r'
  ceph-authtool --create-keyring "$tmp/ceph.mgr.x.keyring" --gen-key -n mgr.x \
    --cap mon 'allow profile mgr' --cap osd 'allow *' --cap mds 'allow *'
  ceph-authtool --create-keyring "$tmp/ceph.mds.a.keyring" --gen-key -n mds.a \
    --cap mon 'allow profile mds' --cap osd 'allow rwx' --cap mds 'allow' --cap mgr 'allow profile mds'
  ceph-authtool --create-keyring "$tmp/ceph.client.rgw.gw.keyring" --gen-key -n client.rgw.gw \
    --cap mon 'allow rw' --cap osd 'allow rwx' --cap mgr 'allow rw'
  local k
  for k in client.admin client.bootstrap-osd mgr.x mds.a client.rgw.gw; do
    ceph-authtool "$tmp/ceph.mon.keyring" --import-keyring "$tmp/ceph.$k.keyring" >/dev/null
  done

  local -a monmap_args=()
  for id in "${MON_IDS[@]}"; do
    ip="$(mon_ip "$id")"
    monmap_args+=(--addv "$id" "[v2:${ip}:3300,v1:${ip}:6789]")
  done
  monmaptool --create --enable-all-features --fsid "$fsid" "${monmap_args[@]}" "$tmp/monmap" >/dev/null

  cat >"$tmp/ceph.conf" <<EOF
# Generated by docker/ceph/entrypoint.sh bootstrap. Lab settings, not production.
[global]
fsid = $fsid
mon_initial_members = $(IFS=,; echo "${MON_IDS[*]}")
mon_host = $mon_host
public_network = ${NET_PREFIX}.0/24
auth_cluster_required = cephx
auth_service_required = cephx
auth_client_required = cephx

# Log to stderr so \`docker compose logs\` shows everything.
log_to_file = false
log_to_stderr = true
err_to_stderr = true
mon_cluster_log_to_file = false

# Replication: 3 copies, keep serving I/O with 2. Failure domain is the OSD
# (chooseleaf type 0), because every OSD lives on the same physical machine.
osd_pool_default_size = 3
osd_pool_default_min_size = 2
osd_crush_chooseleaf_type = 0
# Failure reports must come from 2 distinct subtrees at this level (default:
# host). All OSDs share one host bucket, so count reporters per OSD instead,
# or a dead OSD would only be noticed after the 900s beacon timeout.
mon_osd_reporter_subtree_level = osd

# Demo-friendly timings: a down OSD is marked "out" after 60s (default 600s).
mon_osd_down_out_interval = 60
mon_allow_pool_delete = true
# Docker Desktop's disk is shared with every image and volume on the laptop.
mon_data_avail_warn = 10
# Every client in this lab is current; disable the legacy reclaim path.
auth_allow_insecure_global_id_reclaim = false

[osd]
# File-backed BlueStore: the "block device" is a sparse file inside the OSD's
# volume. No LVM, no ceph-volume, no real disk required.
osd_objectstore = bluestore
bluestore_block_create = true
bluestore_block_size = 5368709120
osd_memory_target = 939524096
# All OSDs share one CRUSH host bucket, which is what this really is.
crush_location = root=default host=docker-desktop

[mds]
mds_cache_memory_limit = 268435456

[client.rgw.gw]
rgw_frontends = beast port=7480
rgw_thread_pool_size = 64
EOF

  chown ceph:ceph "$tmp"/*
  chmod 0600 "$tmp"/*.keyring
  chmod 0644 "$tmp/ceph.conf" "$tmp/monmap"
  # Admin keyring readable by tooling running as root only; that's fine here.
  for k in "$tmp"/*; do
    [[ "$(basename "$k")" == ceph.conf ]] || mv "$k" "$ETC/"
  done
  mv "$tmp/ceph.conf" "$ETC/ceph.conf"
  rmdir "$tmp"
  log "bootstrap complete"
}

# ---------------------------------------------------------------------------
# daemons
# ---------------------------------------------------------------------------
run_mon() {
  local data="/var/lib/ceph/mon/ceph-$DAEMON_ID"
  if [[ ! -e "$data/.initialised" ]]; then
    log "creating mon.$DAEMON_ID store"
    mkdir -p "$data"
    find "$data" -mindepth 1 -delete
    ceph-mon --mkfs -i "$DAEMON_ID" --monmap "$ETC/monmap" --keyring "$ETC/ceph.mon.keyring" --mon-data "$data"
    touch "$data/.initialised"
  fi
  chown -R ceph:ceph "$data" /var/run/ceph
  exec ceph-mon -f -i "$DAEMON_ID" --setuser ceph --setgroup ceph --public-addr "$(mon_ip "$DAEMON_ID")"
}

run_mgr() {
  local data="/var/lib/ceph/mgr/ceph-$DAEMON_ID"
  install_keyring "$ETC/ceph.mgr.$DAEMON_ID.keyring" "$data"
  chown -R ceph:ceph "$data" /var/run/ceph
  exec ceph-mgr -f -i "$DAEMON_ID" --setuser ceph --setgroup ceph
}

run_osd() {
  local data="/var/lib/ceph/osd/ceph-$DAEMON_ID"
  mkdir -p "$data"
  if [[ ! -e "$data/.initialised" ]]; then
    wait_for_cluster
    # Persist uuid+secret before registering, so a retry after a crash
    # re-sends the same request and `osd new` stays idempotent.
    [[ -s "$data/.uuid" ]] || cat /proc/sys/kernel/random/uuid >"$data/.uuid"
    [[ -s "$data/.secret" ]] || ceph-authtool --gen-print-key >"$data/.secret"
    local uuid secret
    uuid="$(cat "$data/.uuid")"
    secret="$(cat "$data/.secret")"
    log "registering osd.$DAEMON_ID (uuid $uuid)"
    printf '{"cephx_secret": "%s"}' "$secret" |
      ceph -n client.bootstrap-osd -k "$ETC/ceph.client.bootstrap-osd.keyring" osd new "$uuid" "$DAEMON_ID" -i - >/dev/null
    ceph-authtool --create-keyring "$data/keyring" --name "osd.$DAEMON_ID" --add-key "$secret" >/dev/null
    find "$data" -mindepth 1 -maxdepth 1 ! -name '.uuid' ! -name '.secret' ! -name keyring -exec rm -rf {} +
    log "creating BlueStore on $data/block (sparse file)"
    ceph-osd --mkfs -i "$DAEMON_ID" --osd-uuid "$uuid" --osd-data "$data" --keyring "$data/keyring"
    rm -f "$data/.secret"
    touch "$data/.initialised"
  fi
  chown -R ceph:ceph "$data" /var/run/ceph
  exec ceph-osd -f -i "$DAEMON_ID" --setuser ceph --setgroup ceph
}

run_mds() {
  local data="/var/lib/ceph/mds/ceph-$DAEMON_ID"
  install_keyring "$ETC/ceph.mds.$DAEMON_ID.keyring" "$data"
  chown -R ceph:ceph "$data" /var/run/ceph
  exec ceph-mds -f -i "$DAEMON_ID" --setuser ceph --setgroup ceph
}

run_rgw() {
  local data="/var/lib/ceph/radosgw/ceph-rgw.$DAEMON_ID"
  install_keyring "$ETC/ceph.client.rgw.$DAEMON_ID.keyring" "$data"
  chown -R ceph:ceph "$data" /var/run/ceph
  exec radosgw -f -n "client.rgw.$DAEMON_ID" -k "$data/keyring" --setuser ceph --setgroup ceph
}

# ---------------------------------------------------------------------------
# init: one-shot cluster configuration once mgr and OSDs are up.
# ---------------------------------------------------------------------------
run_init() {
  wait_for_cluster
  # Also in ceph.conf, but mgr modules (e.g. volumes) read the central config DB.
  ceph config set mon mon_allow_pool_delete true
  log "enabling mgr modules: dashboard, prometheus"
  ceph mgr module enable dashboard
  ceph mgr module enable prometheus
  ceph config set mgr mgr/dashboard/server_addr 0.0.0.0
  ceph config set mgr mgr/dashboard/ssl_server_port 8443
  ceph config set mgr mgr/prometheus/server_addr 0.0.0.0

  # The dashboard needs a TLS cert; a self-signed one is fine for localhost.
  if ! ceph config-key exists mgr/dashboard/crt >/dev/null 2>&1; then
    ceph dashboard create-self-signed-cert
  fi

  log "waiting for the dashboard module to come up"
  until ceph mgr services 2>/dev/null | grep -q dashboard; do sleep 2; done

  # Admin user with a random password. The password lives only in the mon's
  # config-key store (`make up` reads it back from there), never in the repo.
  local pwkey=showcase/dashboard-password pwfile
  if ! ceph config-key exists "$pwkey" >/dev/null 2>&1; then
    ceph config-key set "$pwkey" "Ceph-$(head -c 32 /dev/urandom | base64 | tr -dc 'A-Za-z0-9' | head -c 14)" >/dev/null
  fi
  pwfile="$(mktemp)"
  ceph config-key get "$pwkey" >"$pwfile"
  if ! ceph dashboard ac-user-show admin >/dev/null 2>&1; then
    ceph dashboard ac-user-create admin -i "$pwfile" administrator --force-password >/dev/null
  fi
  rm -f "$pwfile"
  log "init complete"
}

# ---------------------------------------------------------------------------
# health <role>: docker healthcheck, asks the local daemon over its admin socket.
# ---------------------------------------------------------------------------
health() {
  local role="$1" asok
  case "$role" in
    mon)
      asok="/var/run/ceph/ceph-mon.$DAEMON_ID.asok"
      ceph --admin-daemon "$asok" mon_status | grep -Eq '"state": "(leader|peon)"' ;;
    osd)
      asok="/var/run/ceph/ceph-osd.$DAEMON_ID.asok"
      ceph --admin-daemon "$asok" status | grep -q '"state": "active"' ;;
    mgr)
      asok="/var/run/ceph/ceph-mgr.$DAEMON_ID.asok"
      ceph --admin-daemon "$asok" status >/dev/null ;;
    mds)
      asok="/var/run/ceph/ceph-mds.$DAEMON_ID.asok"
      ceph --admin-daemon "$asok" status | grep -Eq '"state": "up:(active|standby|standby-replay)"' ;;
    rgw)
      curl -fsS -o /dev/null "http://127.0.0.1:7480/" ;;
    *) log "unknown health role $role"; return 2 ;;
  esac
}

ROLE="${1:-}"
shift || true
case "$ROLE" in
  bootstrap) bootstrap ;;
  mon) run_mon ;;
  mgr) run_mgr ;;
  osd) run_osd ;;
  mds) run_mds ;;
  rgw) run_rgw ;;
  init) run_init ;;
  health) health "$@" ;;
  *) echo "usage: $0 bootstrap|mon|mgr|osd|mds|rgw|init|health <role>" >&2; exit 2 ;;
esac
